const cache = {};
function build(name) {
  const rows = art[name] || art.spark,
    width = Math.max(...rows.map((r) => r.length)),
    ox = Math.floor((16 - width) / 2),
    oy = Math.floor((16 - rows.length) / 2),
    paths = {};
  rows.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const key = row[x];
      if (!palette[key]) {
        x++;
        continue;
      }
      let run = 1;
      while (row[x + run] === key) run++;
      (paths[key] ??= []).push(`M${x + ox} ${y + oy}h${run}v1h-${run}z`);
      x += run;
    }
  });
  return Object.entries(paths)
    .map(([key, d]) => `<path fill="${palette[key]}" d="${d.join("")}"/>`)
    .join("");
}
export const iconNames = Object.keys(art);
export function icon(name, cls = "") {
  cache[name] ??= build(name);
  return `<svg class="icon pixel-icon ${cls}" viewBox="0 0 16 16" shape-rendering="crispEdges" aria-hidden="true">${cache[name]}</svg>`;
}
